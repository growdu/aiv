"""退出码语义——**契约层说了算**。

    OK = 0            成功
    USAGE = 1         用法错：你给的参数或配置写错了
    PRECONDITION = 2  缺前置条件：东西还没有 / 还不够 / 这一篇不该发
    FAILED = 3        做事失败：接口、写入、解析出错

**为什么是这四个。** 调用方（调度层、CI、流水线）能从退出码上分出三件事：

- ``1`` 是**它自己**写错了参数或命令——重试没有意义，脚本一错就是错；
- ``2`` 是**东西还没准备好**——成片没出、包没建、素材没到。这一档有可能
  等一会儿就成立，所以它跟 ``3`` 分开：``3`` 是做过了、失败了（接口报错、
  写盘失败、源文件解析不了），重试要人来判断，``2`` 有时重试就有用；
- ``3`` 是**做事失败**——已经动手了，结果不对。

**1 与 2 的分界。** 一句话：**「少给一个*命令行*的必填参数」是 1；
「参数没写错，但它指的东西还没有 / 还不够」是 2。**

| 码 | 判据 | 例子 |
| --- | --- | --- |
| 1 用法错 | **你给的参数或配置*写错了***：命令写错、少给*命令行*必填参数（``--url`` / ``--draft-id``）、目录路径配错 | ``mark published`` 少给 ``--url``；能力声明指向的目录配错了 |
| 2 缺前置条件 | **东西还没有 / 还不够**：文章不存在、快照不存在、目录不存在、**内容缺一个必填项**（B站转载没给来源、公众号缺图）、**凭据还没配好**、这一篇不合格（超限等） | 找不到文章；找不到状态快照；B站转载缺 ``source``；公众号还没配 ``WX_APPID``；内容单元目录还没生成 |

**少给一个*命令行*的必填参数**是 1（命令写错了）；
**内容里缺一个必填项**（B站转载没给来源、公众号缺图）是 2——
参数没错，是这一篇现在还不该发。

**（Task 10 之前）** 五个 adapter 各写各的：公众号「找不到」是 1、B站「缺 --url」是 2、
三个视频 adapter 一律 1、argparse 的用法错是 2。同一件事在不同平台有不同
的码，调用方没法写「重试该重试的」。

**谁定义。** 这一层（契约层）定义，各 adapter **读**它。接缝是**文件**不是
import——adapter 不 import 契约层（§11.1 的接缝原则），它读自己平台的能力
声明 ``platforms/<平台>/capability.toml`` 的 ``[exit]`` 段，那一段必须与
这里的表一致（根套件 ``tests/test_exit_codes.py`` 盯着这件事）。

**adapter 怎么读。** 每个平台各有一个读取器（头条与公众号各有自己的
``capability.py``，三个视频 adapter 共用 ``video/pipeline/pyv/epmeta.py``
的 ``load_exit_codes``），读出 ``{"ok": 0, "usage": 1, ...}`` 之后
映射成自己 CLI 用的常量名。**数据是数据**：平台规则变了改 TOML，
不改 Python。
"""

from __future__ import annotations

OK = 0            # 成功
USAGE = 1         # 用法错：你给的参数或配置写错了（少给命令行的必填参数也是这一档）
PRECONDITION = 2  # 缺前置条件：东西还没有 / 还不够 / 这一篇不该发
FAILED = 3        # 做事失败：接口、写入、解析出错

#: 能力声明里 ``[exit]`` 段必须写的四行，与上面四个常量一一对应。
#: 键名是**词汇**：契约层、五个 adapter 的读取器都按这四个名字取。
CANONICAL: dict[str, int] = {"ok": OK, "usage": USAGE,
                              "precondition": PRECONDITION, "failed": FAILED}

__all__ = ["CANONICAL", "FAILED", "OK", "PRECONDITION", "USAGE"]
